#!/usr/bin/env python3
"""Write an SU2 config (.cfg) from physical flight conditions.

The numerics are chosen from the flow regime, so the same call works from a
low-speed UAV to a supersonic case:
  M < 0.3        compressible RANS + Roe/MUSCL, no limiter (or --solver INC_RANS)
  0.3 <= M < 0.75 Roe + MUSCL, no limiter
  M >= 0.75      Roe + MUSCL + Venkatakrishnan limiter (shocks), lower start CFL
Everything is in SI units (SU2 SI system, FREESTREAM_TEMP_EQ initialization).

Examples
  # 2D airfoil, resolved wall, SA
  python write_su2_config.py --mesh mesh.su2 --mach 0.15 --aoa 10 --re 6e6 \
      --lref 1 --T 300 --walls airfoil --far farfield -o case.cfg
  # 3D half-wing at cruise from a flow_conditions.py JSON
  python write_su2_config.py --mesh wing.su2 --cond cond.json --aoa 2 \
      --sref 1.5 --lref 0.75 --walls wing --far farfield --sym symmetry \
      --turb SST -o case.cfg
"""
import argparse, json


def build(a):
    if a.cond:
        c = json.load(open(a.cond))
        a.mach = a.mach or c["mach"]; a.re = a.re or c["reynolds"] / c["lref_m"] * a.lref
        a.T = a.T or c["T_K"]
    if a.mach is None:
        raise SystemExit("need --mach (or --cond)")
    viscous = a.solver in ("RANS", "INC_RANS", "NAVIER_STOKES")
    if viscous and a.re is None:
        raise SystemExit("viscous solver needs --re (or --cond)")
    M = a.mach
    transonic = M >= 0.75
    walls = ", ".join(f"{w}, 0.0" for w in a.walls)
    wall_list = ", ".join(a.walls)
    L = []
    w = L.append
    w("% ---- generated by write_su2_config.py ----")
    w(f"SOLVER= {a.solver}")
    if a.solver in ("RANS", "INC_RANS"):
        w(f"KIND_TURB_MODEL= {a.turb}")
        if a.turb == "SA":
            w("SA_OPTIONS= NONE")
        else:
            # SU2's defaults (5 % intensity, mu_t/mu = 10) are wind-tunnel-like and,
            # on coarse 3D meshes, let SST eddy viscosity grow to ~10^4 everywhere
            # (UAV test: CD 5x too high). Free flight is ~0.1 %.
            w(f"FREESTREAM_TURBULENCEINTENSITY= {a.tu}")
            w(f"FREESTREAM_TURB2LAMVISCRATIO= {a.mut_ratio}")
        if a.wall_functions:
            w(f"MARKER_WALL_FUNCTIONS= ({', '.join(x + ', STANDARD_WALL_FUNCTION' for x in a.walls)})")
    w("MATH_PROBLEM= DIRECT")
    w(f"RESTART_SOL= {'YES' if a.restart else 'NO'}")
    w("SYSTEM_MEASUREMENTS= SI")
    if a.solver.startswith("INC"):
        # Incompressible: specify velocity and density directly
        from math import sqrt, cos, sin, radians
        Vinf = M * sqrt(1.4 * 287.058 * a.T)
        rho = a.rho or (json.load(open(a.cond))["rho"] if a.cond else 1.225)
        mu = rho * Vinf * a.lref / a.re if a.re else 1.8e-5
        w("INC_DENSITY_MODEL= CONSTANT")
        w(f"INC_DENSITY_INIT= {rho:.6g}")
        w(f"INC_VELOCITY_INIT= ( {Vinf*cos(radians(a.aoa)):.6g}, {Vinf*sin(radians(a.aoa)):.6g}, 0.0 )" if not a.three_d else
          f"INC_VELOCITY_INIT= ( {Vinf*cos(radians(a.aoa)):.6g}, 0.0, {Vinf*sin(radians(a.aoa)):.6g} )")
        w("INC_NONDIM= DIMENSIONAL")
        w("VISCOSITY_MODEL= CONSTANT_VISCOSITY")
        w(f"MU_CONSTANT= {mu:.6g}")
        w(f"REF_AREA= {a.sref or 0}")
        w(f"REF_LENGTH= {a.lref}")
        w(f"MARKER_HEATFLUX= ({walls})" if viscous else f"MARKER_EULER= ({wall_list})")
        w(f"MARKER_FAR= ({', '.join(a.far)})")
    else:
        w(f"MACH_NUMBER= {M}")
        w(f"AOA= {a.aoa}")
        w(f"SIDESLIP_ANGLE= {a.beta}")
        w(f"FREESTREAM_TEMPERATURE= {a.T}")
        w("INIT_OPTION= REYNOLDS" if viscous else "INIT_OPTION= TD_CONDITIONS")
        if viscous:
            w(f"REYNOLDS_NUMBER= {a.re:.6g}")
            w(f"REYNOLDS_LENGTH= {a.lref}")
        else:
            w(f"FREESTREAM_PRESSURE= {a.p}")
        w("FREESTREAM_OPTION= TEMPERATURE_FS")
        w("REF_DIMENSIONALIZATION= DIMENSIONAL")
        w("FLUID_MODEL= STANDARD_AIR")
        w("GAMMA_VALUE= 1.4")
        w("GAS_CONSTANT= 287.058")
        if viscous:
            w("VISCOSITY_MODEL= SUTHERLAND")
            w("MU_REF= 1.716E-5"); w("MU_T_REF= 273.15"); w("SUTHERLAND_CONSTANT= 110.4")
        w(f"REF_ORIGIN_MOMENT_X= {a.xmom}"); w("REF_ORIGIN_MOMENT_Y= 0.0"); w("REF_ORIGIN_MOMENT_Z= 0.0")
        w(f"REF_LENGTH= {a.lref}")
        w(f"REF_AREA= {a.sref or 0}")
        if viscous:
            w(f"MARKER_HEATFLUX= ({walls})")
        else:
            w(f"MARKER_EULER= ({wall_list})")
        w(f"MARKER_FAR= ({', '.join(a.far)})")
    if a.sym:
        w(f"MARKER_SYM= ({', '.join(a.sym)})")
    w(f"MARKER_PLOTTING= ({wall_list})")
    w(f"MARKER_MONITORING= ({wall_list})")
    # ---- numerics ----
    w("NUM_METHOD_GRAD= WEIGHTED_LEAST_SQUARES")
    w(f"CFL_NUMBER= {a.cfl or (5.0 if transonic else 10.0)}")
    w("CFL_ADAPT= YES")
    # CFL capped at 50 (25 transonic): higher values made hybrid quad/tri meshes
    # oscillate without converging in testing.
    w(f"CFL_ADAPT_PARAM= ( 0.5, 1.1, {1.0 if transonic else 5.0}, {a.cfl_max or (25 if transonic else 50)} )")
    w("ITER= %d" % a.iter)
    w("LINEAR_SOLVER= FGMRES"); w("LINEAR_SOLVER_PREC= ILU")
    w("LINEAR_SOLVER_ERROR= 1E-4"); w("LINEAR_SOLVER_ITER= 15")
    w("CONV_NUM_METHOD_FLOW= " + ("FDS" if a.solver.startswith("INC") else "ROE"))
    w("MUSCL_FLOW= YES")
    # An edge limiter is needed even subsonic on unstructured/hybrid meshes:
    # with NONE the NACA0012 validation stalled at ~0.5 orders of residual drop.
    w("SLOPE_LIMITER_FLOW= " + ("VENKATAKRISHNAN" if transonic else "VAN_ALBADA_EDGE"))
    w("VENKAT_LIMITER_COEFF= 0.05")
    w("TIME_DISCRE_FLOW= EULER_IMPLICIT")
    if a.solver in ("RANS", "INC_RANS"):
        w("CONV_NUM_METHOD_TURB= SCALAR_UPWIND"); w("MUSCL_TURB= NO")
        w("TIME_DISCRE_TURB= EULER_IMPLICIT"); w("CFL_REDUCTION_TURB= 1.0")
    # ---- convergence ----
    w("CONV_FIELD= " + ("RMS_PRESSURE" if a.solver.startswith("INC") else "RMS_DENSITY"))
    w(f"CONV_RESIDUAL_MINVAL= {a.resmin}")
    w("CONV_STARTITER= 10")
    # ---- output ----
    w(f"MESH_FILENAME= {a.mesh}")
    w("MESH_FORMAT= SU2")
    w("OUTPUT_FILES= (RESTART, PARAVIEW, SURFACE_CSV, SURFACE_PARAVIEW)")
    w("VOLUME_OUTPUT= (COORDINATES, SOLUTION, PRIMITIVE)")
    w("HISTORY_OUTPUT= (ITER, RMS_RES, AERO_COEFF, CFL_NUMBER)")
    sc = "(INNER_ITER, RMS_DENSITY, LIFT, DRAG, MOMENT_Z)" if not a.three_d else \
         "(INNER_ITER, RMS_DENSITY, LIFT, DRAG, MOMENT_Y)"
    if a.solver.startswith("INC"):
        sc = sc.replace("RMS_DENSITY", "RMS_PRESSURE")
    w(f"SCREEN_OUTPUT= {sc}")
    w("SCREEN_WRT_FREQ_INNER= 50")
    w("OUTPUT_WRT_FREQ= 500")
    w("TABULAR_FORMAT= CSV")
    w("CONV_FILENAME= history"); w("RESTART_FILENAME= restart.dat")
    w("SOLUTION_FILENAME= restart.dat")
    w("VOLUME_FILENAME= flow"); w("SURFACE_FILENAME= surface_flow")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mesh", required=True)
    ap.add_argument("--solver", default="RANS",
                    choices=["RANS", "EULER", "NAVIER_STOKES", "INC_RANS", "INC_EULER"])
    ap.add_argument("--turb", default="SA", choices=["SA", "SST"])
    ap.add_argument("--tu", type=float, default=0.001,
                    help="SST freestream turbulence intensity (0.001 = 0.1 %%, free flight)")
    ap.add_argument("--mut-ratio", type=float, default=1.0,
                    help="SST freestream eddy/laminar viscosity ratio")
    ap.add_argument("--wall-functions", action="store_true",
                    help="use when wall y+ is 30-100 (coarse 3D meshes)")
    ap.add_argument("--cond", help="JSON from flow_conditions.py")
    ap.add_argument("--mach", type=float)
    ap.add_argument("--aoa", type=float, default=0.0)
    ap.add_argument("--beta", type=float, default=0.0, help="sideslip [deg]")
    ap.add_argument("--re", type=float, help="Reynolds number based on --lref")
    ap.add_argument("--T", type=float, default=288.15, help="static temperature [K]")
    ap.add_argument("--p", type=float, default=101325.0, help="static pressure [Pa] (Euler)")
    ap.add_argument("--rho", type=float, help="density for INC_RANS [kg/m^3]")
    ap.add_argument("--lref", type=float, required=True, help="reference chord [m]")
    ap.add_argument("--sref", type=float, help="reference area [m^2] (2D: chord)")
    ap.add_argument("--xmom", type=float, default=0.25, help="moment ref x [m]")
    ap.add_argument("--walls", nargs="+", required=True)
    ap.add_argument("--far", nargs="+", default=["farfield"])
    ap.add_argument("--sym", nargs="*")
    ap.add_argument("--three-d", action="store_true", help="3D case (z up, lift along z)")
    ap.add_argument("--iter", type=int, default=3000)
    ap.add_argument("--resmin", type=float, default=-8.0)
    ap.add_argument("--cfl", type=float, help="starting CFL")
    ap.add_argument("--cfl-max", type=float, help="adaptive CFL ceiling")
    ap.add_argument("--restart", action="store_true")
    ap.add_argument("-o", "--out", default="case.cfg")
    a = ap.parse_args()
    open(a.out, "w").write(build(a))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
